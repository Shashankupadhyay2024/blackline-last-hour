#!/usr/bin/env python3
"""Generate the voice pack: every MAYA/EVAN/SILAS/VOSS line in src/*.js is synthesized with
Piper neural TTS (offline), encoded as Opus and embedded into src/voicepack.js.
Also generates enemy combat barks with several different voices.
Usage: python3 tools/make_voices.py   (needs: pip install piper-tts, ffmpeg, voice models in ~/voices)"""
import re, pathlib, subprocess, base64, wave, json, hashlib, os, sys
from piper import PiperVoice, SynthesisConfig
ROOT = pathlib.Path(__file__).resolve().parent.parent
VD = pathlib.Path(os.environ.get('VOICES', '/home/claude/voices'))
CACHE = ROOT / 'tools' / '.voicecache'; CACHE.mkdir(exist_ok=True)
def djb2(s):
    h = 5381
    for ch in s: h = ((h * 33) ^ ord(ch)) & 0xFFFFFFFF
    return format(h, 'x')
def unesc(s): return re.sub(r"\\(.)", r"\1", s)
def spoken(s):
    s = re.sub(r'<[^>]+>', '', s); s = re.sub(r'\([^)]*\)', '', s); s = re.sub(r'\[[^\]]*\]', '', s)
    s = s.replace('—', ', ').replace('…', '...').replace('HWY', 'Highway').replace('Hwy', 'Highway')
    return re.sub(r'\s+', ' ', s).strip(' ,')
lines = {}
for f in sorted((ROOT / 'src').glob('*.js')):
    if f.name == 'voicepack.js': continue
    src = f.read_text(encoding='utf-8')
    for who, txt in re.findall(r"\[\s*'(MAYA|EVAN|SILAS|VOSS)'\s*,\s*'((?:[^'\\]|\\.)*)'", src): lines[unesc(txt)] = who
    for cls, txt in re.findall(r'<span class="(ev|my|si)">(?:EVAN|MAYA|SILAS)</span>\s*((?:[^\'\\]|\\.)*?)\'\]', src): lines[unesc(txt)] = {'ev': 'EVAN', 'my': 'MAYA', 'si': 'SILAS'}[cls]
BARKS = {'contact': ['Contact!', 'Enemy spotted!', 'There he is!', 'Target sighted!'], 'reload': ['Reloading!', 'Cover me, reloading!'],
         'grenade': ['Grenade!', 'Get down!', 'Frag out!'], 'down': ['Man down!', 'We lost one!', 'He got Miller!'],
         'search': ['Where did he go?', 'Check the corners.', 'He is here somewhere.'], 'flank': ['Flanking left!', 'Moving up!', 'Push him!'],
         'hit': ['Agh!', 'I am hit!', 'Ugh!']}
SPEAKERS = [12, 45, 98, 214, 350]
models = {}
def voice(name):
    if name not in models: models[name] = PiperVoice.load(str(VD / name / f'{name}.onnx'))
    return models[name]
def render(text, model, cfg, key):
    out = CACHE / f'{key}.ogg'
    if not out.exists():
        wav = CACHE / f'{key}.wav'
        with wave.open(str(wav), 'wb') as w: voice(model).synthesize_wav(text, w, syn_config=cfg)
        subprocess.run(['ffmpeg', '-loglevel', 'error', '-y', '-i', str(wav), '-af', 'highpass=f=70,loudnorm=I=-16:TP=-1.5', '-ac', '1', '-c:a', 'libopus', '-b:a', '28k', '-application', 'voip', str(out)], check=True)
        wav.unlink()
    return base64.b64encode(out.read_bytes()).decode()
pack, n = {}, 0
for txt, who in lines.items():
    sp = spoken(txt)
    if not sp: continue
    # Maya: Lessac · Evan: Ryan · Silas Kade: LibriTTS #342 (low, slow) · Dr. Voss: LibriTTS #837
    model = {'MAYA': 'en-us-lessac-medium', 'EVAN': 'en-us-ryan-high'}.get(who, 'en-us-libritts-high')
    spk = {'SILAS': 342, 'VOSS': 837}.get(who)
    cfg = SynthesisConfig(speaker_id=spk, length_scale={'MAYA': 0.94, 'SILAS': 1.08, 'VOSS': 1.04}.get(who, 1.0), noise_scale=0.6, noise_w_scale=0.75)
    key = hashlib.md5((model + str(spk) + sp).encode()).hexdigest()[:12] if spk is not None else hashlib.md5((model + sp).encode()).hexdigest()[:12]
    pack[djb2(txt)] = render(sp, model, cfg, key); n += 1
barks = {}
for kind, texts in BARKS.items():
    barks[kind] = []
    for i, t in enumerate(texts):
        for spk in SPEAKERS[i % 2::2][:2]:
            key = hashlib.md5(f'bark{spk}{t}'.encode()).hexdigest()[:12]
            barks[kind].append(render(t, 'en-us-libritts-high', SynthesisConfig(speaker_id=spk, length_scale=0.85, noise_scale=0.7), key))
js = '/* generated by tools/make_voices.py — Piper neural TTS (offline), Opus */\nconst VOICEPACK = ' + json.dumps(pack) + ';\nconst BARKPACK = ' + json.dumps(barks) + ';\n'
(ROOT / 'src' / 'voicepack.js').write_text(js, encoding='utf-8')
print(f'{n} dialogue lines, {sum(len(v) for v in barks.values())} barks, {len(js)/1024/1024:.1f} MB')
